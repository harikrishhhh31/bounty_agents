"""Schemathesis adapter (schema/property-based API testing).

This module is a thin, argv-only adapter over the Schemathesis v4 CLI. It follows
the shared contract in :mod:`bugbounty.tool_adapters` so the core scanner keeps
working when Schemathesis is not installed.

Target/schema duality
---------------------
The rest of the platform speaks in *endpoint URLs* (e.g. a single HTTP endpoint
or an API base URL), while Schemathesis consumes a *schema location* (an OpenAPI
document file or URL, a GraphQL SDL, or a gRPC descriptor). This adapter treats
the engine-provided ``target`` as that schema location and validates it as an
``http(s)`` URL. When the schema is reachable but the API under test lives at a
different base URL, callers pass the extra ``--url <base-url>`` flag through
``AdapterConfig.extra_args`` (or point ``target`` directly at the OpenAPI
document, e.g. ``https://api.example.com/openapi.json``).

Report handling
---------------
Schemathesis emits JUnit XML to a file rather than stdout, so ``build_command``
writes a small temporary ``schemathesis.toml`` that pins ``[reports.junit]`` to a
known path and runs with ``--config-file``. ``output_file`` locates that TOML in
the argv, reads the configured path back, and the base runner feeds the file
contents to :meth:`SchemathesisAdapter.parse_output`.
"""

from __future__ import annotations

import os
import re
import tempfile
import xml.etree.ElementTree as ET
from pathlib import Path
from typing import Any, Iterable, Mapping, Sequence

from .tool_adapters import (
    AdapterConfig,
    BaseSubprocessAdapter,
    InputValidationError,
    ToolExecution,
    ToolFindingRecord,
    redact_command,
    redact_sensitive,
    validate_target_url,
)

# Bounded evidence keeps persisted findings small even for verbose failure text.
_EVIDENCE_STRING_LIMIT = 2000
_JUNIT_FILENAME = "schemathesis-junit.xml"
_TOML_FILENAME = "schemathesis.toml"


def _local_name(tag: Any) -> str:
    """Return the local part of an XML tag, ignoring any namespace prefix."""

    text = tag if isinstance(tag, str) else str(tag)
    return text.rsplit("}", 1)[-1] if "}" in text else text


def _bounded(value: Any, limit: int = _EVIDENCE_STRING_LIMIT) -> Any:
    if isinstance(value, str):
        return value[:limit]
    return value


class SchemathesisAdapter(BaseSubprocessAdapter):
    """Adapter for the Schemathesis v4 CLI (``schemathesis`` / ``st``)."""

    name = "schemathesis"
    executable_names = ("schemathesis", "st", "schemathesis.exe")

    def version_command(self, executable: str) -> tuple[str, ...]:
        return (executable, "--version")

    # -- configuration file generation -------------------------------------

    def _write_config(self) -> str:
        """Write a temporary TOML pinning the JUnit report path; return its path."""

        config_dir = tempfile.mkdtemp(prefix="schemathesis-adapter-")
        junit_path = os.path.join(config_dir, _JUNIT_FILENAME)
        toml_path = os.path.join(config_dir, _TOML_FILENAME)
        # TOML basic strings interpret backslash escapes, so emit forward slashes
        # to keep Windows paths valid without escaping.
        toml_junit_path = junit_path.replace("\\", "/")
        content = (
            "# Generated by bugbounty SchemathesisAdapter\n"
            "[reports.junit]\n"
            f'path = "{toml_junit_path}"\n'
        )
        with open(toml_path, "w", encoding="utf-8") as handle:
            handle.write(content)
        return toml_path

    @staticmethod
    def _junit_path_from_toml(text: str) -> str | None:
        match = re.search(r"""^\s*path\s*=\s*(['"])(.*?)\1\s*$""", text, re.MULTILINE)
        if not match:
            return None
        return match.group(2) or None

    @staticmethod
    def _find_config_file(command: Sequence[str]) -> str | None:
        try:
            parts = list(command)
        except TypeError:
            return None
        for index, part in enumerate(parts):
            if part == "--config-file" and index + 1 < len(parts):
                return parts[index + 1]
            if isinstance(part, str) and part.startswith("--config-file="):
                return part.split("=", 1)[1]
        return None

    # -- command construction ----------------------------------------------

    def build_command(self, target: str, config: AdapterConfig | None = None) -> tuple[str, ...]:
        """Build the Schemathesis argv for one schema location.

        ``target`` is interpreted as the *schema location* (OpenAPI/GraphQL/gRPC)
        and validated as an ``http(s)`` URL. Add ``--url <base-url>`` via
        ``extra_args`` when the schema and the API base URL differ.
        """

        cfg = config or AdapterConfig()
        exe = self.resolve_executable() or self.executable_names[0]
        schema_location = validate_target_url(target)
        toml_path = self._write_config()
        args: list[str] = [
            exe,
            "--config-file",
            toml_path,
            "run",
            schema_location,
            "--report=junit",
        ]
        args.extend(str(arg) for arg in cfg.extra_args)
        return tuple(args)

    def output_file(self, command: Sequence[str], config: AdapterConfig) -> str | None:
        """Return the JUnit XML path referenced by the generated TOML.

        Locates the ``--config-file`` TOML in ``command``, reads the configured
        ``path`` back, and falls back to a deterministic temp path. Never raises.
        """

        try:
            toml_path = self._find_config_file(command)
            if toml_path:
                try:
                    text = Path(toml_path).read_text(encoding="utf-8", errors="replace")
                except OSError:
                    text = ""
                found = self._junit_path_from_toml(text)
                if found:
                    return found
        except Exception:
            pass
        try:
            return os.path.join(tempfile.gettempdir(), _JUNIT_FILENAME)
        except Exception:
            return None

    # -- output parsing -----------------------------------------------------

    def parse_output(self, stdout: str, stderr: str = "") -> list[dict[str, Any]]:
        """Parse a JUnit XML report into one dict per failing ``<testcase>``.

        Returns ``[]`` for empty, non-XML, or malformed input; this method never
        raises so a broken report can never abort a scan.
        """

        if not isinstance(stdout, str) or not stdout.strip():
            return []
        text = stdout.strip()
        if text.startswith("\ufeff"):
            text = text[1:].lstrip()
        try:
            root = ET.fromstring(text)
        except Exception:
            return []

        items: list[dict[str, Any]] = []
        try:
            for element in root.iter():
                if _local_name(element.tag) != "testcase":
                    continue
                failure = None
                for child in element:
                    if _local_name(child.tag) == "failure":
                        failure = child
                        break
                if failure is None:
                    continue
                items.append(
                    {
                        "name": element.get("name") or "",
                        "classname": element.get("classname") or "",
                        "failure_message": failure.get("message") or "",
                        "failure_type": failure.get("type") or "",
                        "failure_text": (failure.text or "").strip(),
                    }
                )
        except Exception:
            return items
        return items

    # -- normalization ------------------------------------------------------

    def normalize_results(
        self,
        raw_items: Iterable[Mapping[str, Any]],
        *,
        target: str,
        execution: ToolExecution | None = None,
    ) -> tuple[ToolFindingRecord, ...]:
        findings: list[ToolFindingRecord] = []
        for item in raw_items:
            if not isinstance(item, Mapping):
                continue
            name = str(item.get("name") or "").strip()
            classname = str(item.get("classname") or "").strip()
            failure_message = str(item.get("failure_message") or "").strip()
            failure_type = str(item.get("failure_type") or "").strip()

            title = name or "Schemathesis property failure"
            evidence = redact_sensitive(
                {
                    "classname": classname,
                    "failure_type": failure_type,
                    "failure_message": failure_message,
                }
            )
            if not isinstance(evidence, dict):
                evidence = {
                    "classname": classname,
                    "failure_type": failure_type,
                    "failure_message": failure_message,
                }
            evidence = {str(key): _bounded(value) for key, value in evidence.items()}

            provenance = {
                "tool": self.name,
                "tool_version": execution.version if execution else self.version(),
                "target": target,
                "command": redact_command(list(execution.command)) if execution else None,
            }

            raw = redact_sensitive(dict(item))
            if not isinstance(raw, dict):
                raw = {"value": raw}

            description = failure_message or f"Schemathesis reported a failing test case: {title}"

            findings.append(
                ToolFindingRecord(
                    source_tool=self.name,
                    source_id=name or classname or "schemathesis",
                    title=title,
                    category="external-schemathesis",
                    endpoint=target,
                    severity="medium",
                    confidence=0.6,
                    status="candidate",
                    description=description,
                    evidence=evidence,
                    provenance=provenance,
                    raw=raw,
                )
            )
        return tuple(findings)


__all__ = ["SchemathesisAdapter"]
